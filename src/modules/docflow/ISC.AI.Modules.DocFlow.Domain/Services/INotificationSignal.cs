namespace ISC.AI.Modules.DocFlow.Domain.Services;

/// <summary>
/// Внутрисерверная шина «у пользователя изменилась лента уведомлений» — живое обновление
/// колокольчика и ленты без поллинга (разд. 5 ТЗ СКИД). Blazor Server сам доставляет обновление
/// в браузер по своему SignalR-каналу — шина лишь будит подписанные circuit-компоненты.
/// </summary>
/// <remarks>
/// ИНВАРИАНТ (решётка доступа, ТБ-020/021): шина переносит ТОЛЬКО факт «перечитай свою ленту» —
/// ни текст, ни состав уведомлений. Содержимое подписчик получает обычным запросом, где фильтр
/// допуска применяется на выборке; иначе шина стала бы обходным каналом мимо решётки.
/// </remarks>
public interface INotificationSignal
{
    /// <summary>
    /// Сообщить, что у перечисленных получателей изменилась лента. Вызов НЕ ждёт подписчиков
    /// (fire-and-forget): писатель уведомления не должен зависеть от чужих открытых страниц.
    /// </summary>
    void Publish(IReadOnlyCollection<int> recipientUserIds);

    /// <summary>
    /// Подписать колбэк на сигналы ОДНОГО пользователя (свой идентификатор — из контекста доступа).
    /// Возвращённый объект отписывает при Dispose — компонент обязан отписаться при разрушении.
    /// </summary>
    IDisposable Subscribe(int userId, Func<Task> callback);
}
