namespace ISC.AI.Modules.DocFlow.Domain.Services;

/// <summary>Насколько подразделение задействовано в документообороте.</summary>
/// <param name="Documents">Документов, где подразделение указано владельцем.</param>
/// <param name="Assignments">Назначений (поручений) на это подразделение.</param>
public sealed record DivisionUsage(int Documents, int Assignments)
{
    /// <summary>Подразделение нигде не используется — его можно удалить.</summary>
    public bool IsEmpty => Documents == 0 && Assignments == 0;

    /// <summary>Ничего не найдено — значение по умолчанию для отсутствующего ключа.</summary>
    public static DivisionUsage None { get; } = new(0, 0);
}

/// <summary>
/// Сколько документов и поручений привязано к подразделениям.
/// </summary>
/// <remarks>
/// ЗАЧЕМ ОТДЕЛЬНЫЙ ПОРТ. Справочник подразделений ведёт ПРОФИЛЬ (схема <c>inspector</c>), допуски
/// живут в ЯДРЕ (<c>core.clearance</c>), а поручения — в МОДУЛЕ (<c>docflow</c>). Это три разные
/// схемы под тремя контекстами: соединить их одним SQL-запросом нельзя, а лезть профилем в таблицы
/// модуля — значит сломать границу, ради которой модуль и выделяли (ADR-0017).
///
/// Направление зависимости здесь ОБРАТНОЕ обычному и это правильно: профиль знает про модуль
/// (он его подключает), модуль про профиль — нет. Поэтому спрашивает профиль, а отвечает модуль.
///
/// Ответ — СЛОВАРЬ на все подразделения сразу, а не «сколько у подразделения N»: справочник рисуется
/// списком, и поштучный вопрос дал бы по запросу к базе на строку.
/// </remarks>
public interface IDivisionUsage
{
    /// <summary>Использование по всем подразделениям, у которых оно есть (остальных в словаре нет).</summary>
    Task<IReadOnlyDictionary<int, DivisionUsage>> CountAsync(CancellationToken cancellationToken = default);
}
