namespace ISC.AI.Modules.DocFlow.Domain.Enums;

/// <summary>
/// Группа типа документа (ТЗ СКИД §1.4) — определяет поведение системы для документов этого типа.
/// Значения фиксированы CHECK-ограничением БД; изменение группы у типа с документами запрещено (§3.1).
/// </summary>
public enum DocumentGroup
{
    /// <summary>«Хранение»: документ регистрируется и хранится; назначения и статусы исполнения не применяются.</summary>
    Storage = 1,

    /// <summary>«Исполнение»: создаются назначения на подразделения; каждое проходит цепочку статусов независимо.</summary>
    Execution = 2,
}
