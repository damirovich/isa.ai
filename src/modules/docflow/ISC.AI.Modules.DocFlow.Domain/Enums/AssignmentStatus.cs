namespace ISC.AI.Modules.DocFlow.Domain.Enums;

/// <summary>
/// Статус назначения (ТЗ СКИД §4.2): каждое назначение проходит цепочку НЕЗАВИСИМО от других назначений
/// того же документа. Правила переходов — §4.5 (переносятся со сценариями, этап 3 Э4-35);
/// «Просрочено» ставит система автоматически; «Снято с контроля» — только Руководитель.
/// </summary>
public enum AssignmentStatus
{
    /// <summary>Зарегистрировано (автоматически при создании назначения).</summary>
    Registered = 1,

    /// <summary>Контроль — информационный маркер с указанием контролёра; на процесс не влияет.</summary>
    InControl = 2,

    /// <summary>В работе.</summary>
    InProgress = 3,

    /// <summary>Частично исполнено.</summary>
    PartiallyDone = 4,

    /// <summary>Исполнено.</summary>
    Done = 5,

    /// <summary>Просрочено (система, автоматически по истечении срока).</summary>
    Overdue = 6,

    /// <summary>Снято с контроля — финальный статус (только Руководитель).</summary>
    Closed = 7,
}
