namespace ISC.AI.Modules.Media.Domain.Model;

/// <summary>Вид носителя (ТС-010): изображение, видеозапись или аудиозапись.</summary>
public enum MediaKind
{
    /// <summary>Фотография / изображение (JPEG, PNG и т.д.).</summary>
    Image = 1,

    /// <summary>Видеозапись (раскадровывается на кадры, ТС-011; звуковая дорожка расшифровывается, ADR-0026).</summary>
    Video = 2,

    /// <summary>
    /// Аудиозапись (голосовые сообщения, записи разговоров, диктофон; ADR-0026). Лиц в ней нет — поиск по
    /// лицу к ней неприменим; материал дела она даёт расшифровкой с таймкодами.
    /// </summary>
    Audio = 3,
}

/// <summary>
/// Состояние индексации носителя (ТП-004): загружен → в обработке → проиндексирован / ошибка.
/// Поиск (ТС-012) видит только шаблоны проиндексированных носителей — незавершённая обработка
/// не даёт ни ложных «нет», ни половинчатых «да».
/// </summary>
public enum MediaIndexStatus
{
    /// <summary>Файл принят и сохранён; конвейер ещё не запускался.</summary>
    Uploaded = 0,

    /// <summary>Конвейер (кадры → детекция → векторизация) выполняется.</summary>
    Processing = 1,

    /// <summary>Все лица и шаблоны записаны, носитель участвует в поиске.</summary>
    Indexed = 2,

    /// <summary>Обработка не удалась; причина — в <c>IndexError</c>. Повторный запуск — вручную.</summary>
    Failed = 3,

    /// <summary>
    /// Поиск по лицу к носителю неприменим (аудиозапись): конвейер лиц не запускается и не будет запущен.
    /// Отдельное значение, а не «проиндексирован с нулём лиц»: иначе карточка и журнал утверждали бы, что
    /// биометрия обрабатывалась, хотя её здесь нет и быть не может.
    /// </summary>
    NotApplicable = 4,
}

/// <summary>
/// Состояние расшифровки речи носителя (ADR-0026): аудио и звуковая дорожка видео. Живёт отдельно от
/// индексации лиц: это другой конвейер, другая модель и другой сбой — неудача одного не должна
/// выдаваться за неудачу другого.
/// </summary>
public enum TranscriptStatus
{
    /// <summary>Расшифровка к носителю неприменима (изображение).</summary>
    NotApplicable = 0,

    /// <summary>Поставлена в очередь, ещё не начиналась.</summary>
    Pending = 1,

    /// <summary>Выполняется.</summary>
    Processing = 2,

    /// <summary>Фрагменты записаны (их может быть ноль — в записи не нашлось речи).</summary>
    Done = 3,

    /// <summary>Не удалась; причина — в <c>TranscriptError</c>. Повторный запуск — вручную.</summary>
    Failed = 4,
}
