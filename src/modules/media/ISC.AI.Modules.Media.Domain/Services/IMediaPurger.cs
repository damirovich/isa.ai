using ISC.AI.Modules.Media.Domain.Model;

namespace ISC.AI.Modules.Media.Domain.Services;

/// <summary>
/// Гарантированное удаление носителя и ВСЕХ производных — кадров, лиц, шаблонов, файлов исходника и
/// вырезок (ТБ-064 применительно к биометрии, ТБ-075, GATE-6). Реализация — <c>Media.Data</c>.
/// </summary>
/// <remarks>
/// FAIL-CLOSED порядок (как у <c>DocumentPurger</c> ядра): запись в неизменяемый аудит идёт ПЕРВОЙ;
/// недоступен журнал — удаление не выполняется. Строки БД снимаются одной транзакцией (каскад FK
/// внутри схемы <c>media</c>), файлы — после фиксации транзакции (файл без строки безвреден и
/// подбирается сборщиком; строка без файла — нет).
/// </remarks>
public interface IMediaPurger
{
    /// <summary>Удаляет носитель по идентификатору; отсутствующий — идемпотентный no-op без аудита.</summary>
    Task<MediaPurgeResult> PurgeAsync(int assetId, int? subjectId = null, CancellationToken cancellationToken = default);

    /// <summary>
    /// Снимает БИОМЕТРИЧЕСКИЙ СЛОЙ с перечисленных носителей, оставляя сами носители: удаляет шаблоны
    /// лиц (векторы и записи индекса) и файлы вырезок. Носители, кадры и сами лица — с координатами,
    /// таймкодами и привязками к фигурантам — сохраняются.
    /// </summary>
    /// <param name="assetIds">Носители, с которых снимается биометрия (обычно — все носители дела).</param>
    /// <param name="reason">Основание в журнал: почему шаблоны снимаются (например, «закрытие дела №…»).</param>
    /// <param name="subjectId">Кто инициировал (для аудита).</param>
    /// <param name="cancellationToken">Токен отмены.</param>
    /// <remarks>
    /// ЗАЧЕМ ОТДЕЛЬНАЯ ОПЕРАЦИЯ, А НЕ <see cref="PurgeAsync"/>. Шаблон — специальная категория
    /// персональных данных (ТБ-070) и хранится, пока есть законное основание; носитель и результат
    /// работы по нему — материалы дела и хранятся по правилам дела. ТБ-074 требует удалять по
    /// закрытию дела именно ШАБЛОНЫ материалов, а ТФ-ДЕЛ-04 прямо оставляет носители и документы.
    /// Поэтому здесь снимается ровно то, чем ведётся поиск по лицу: после вызова прежняя проба не
    /// находит эти лица (проверяемое условие GATE-6), а «все появления» фигуранта (ТФ-ПЕР-02),
    /// решения верификации и оригиналы носителей остаются как результат расследования.
    ///
    /// Вырезки лиц удаляются вместе с шаблонами: это тоже биометрия (ТБ-070), нужна она была для
    /// разбора кандидатов, и хранить её после закрытия дела не на чем.
    ///
    /// Порядок — FAIL-CLOSED, как у <see cref="PurgeAsync"/>: аудит по каждому носителю ПЕРВЫМ
    /// (недоступен журнал — ничего не удаляется), затем одна транзакция, файлы — после её фиксации.
    /// Операция идемпотентна: повторный вызов по тем же носителям удалять нечего и аудита не пишет.
    /// </remarks>
    Task<TemplatePurgeResult> PurgeTemplatesAsync(
        IReadOnlyCollection<int> assetIds,
        string reason,
        int? subjectId = null,
        CancellationToken cancellationToken = default);

    /// <summary>
    /// Удаляет ИСТОРИЮ ПОИСКОВ дела: все поисковые сессии, начатые в этом деле, с кандидат-листами,
    /// решениями верификации и файлами вырезок проб (ТБ-064, ТНД-008, ADR-0025). Носители здесь не
    /// трогаются — их удаляет <see cref="PurgeAsync"/>, по одному, решением вызывающего.
    /// </summary>
    /// <param name="caseRef">Дело (непрозрачный идентификатор профиля), чья история поисков удаляется.</param>
    /// <param name="reason">Основание в журнал (например, «уничтожение дела №…: основание …»).</param>
    /// <param name="subjectId">Кто инициировал (для аудита).</param>
    /// <param name="cancellationToken">Токен отмены.</param>
    /// <remarks>
    /// ПОЧЕМУ ОТДЕЛЬНО ОТ НОСИТЕЛЕЙ. Сессия принадлежит делу, в котором искали, а кандидаты в ней —
    /// лица из ЛЮБЫХ доступных дел. Поэтому удаляются сессии ЭТОГО дела целиком (вместе с их
    /// кандидатами), а кандидаты в сессиях ДРУГИХ дел, указывающие на носители этого дела, остаются: это
    /// история чужого дела, и её переписывать нельзя (ТБ-072). Полный кандидат-лист каждого поиска
    /// и без того хранится в неизменяемом журнале.
    ///
    /// Порядок — FAIL-CLOSED, как у <see cref="PurgeAsync"/>: запись в журнал ПЕРВОЙ (недоступен журнал —
    /// ничего не удаляется), затем одна транзакция (кандидаты и решения уходят каскадом БД), файлы
    /// вырезок проб — после фиксации. Нет сессий — идемпотентный no-op без аудита.
    /// </remarks>
    Task<CaseSearchPurgeResult> PurgeCaseSearchesAsync(
        int caseRef,
        string reason,
        int? subjectId = null,
        CancellationToken cancellationToken = default);
}
