namespace ISC.AI.Modules.Media.Domain.Services;

/// <summary>
/// ПОРТ ПРОФИЛЯ (необязательный, ADR-0059): адреса карточек профиля для переходов со страниц пакета — «К карточке дела»
/// в медиатеке дела и карточке носителя, имя фигуранта в легенде ленты видео. Пакет понятий «дело» и «фигурант» не
/// имеет и маршрутов профиля не знает (ТС-003, ADR-0017) — адрес даёт профиль. Без реализации профиля действует
/// поставка пакета «без ссылок»: страницы работают, просто не показывают переходов.
/// </summary>
/// <remarks>
/// ИНВАРИАНТ (ТБ-020/021): адрес — только навигация, не право. Страница профиля по нему сама применяет решётку и роль;
/// пакет спрашивает адрес лишь для дела и фигурантов, уже отданных портом <see cref="ICaseScope"/> под решёткой
/// субъекта, — ссылка не раскрывает ничего сверх того, что страница уже показала.
/// </remarks>
public interface IMediaLinks
{
    /// <summary>Адрес карточки дела в интерфейсе профиля; <see langword="null"/> — перехода нет.</summary>
    /// <param name="caseId">Дело (непрозрачный идентификатор профиля).</param>
    string? CaseCard(int caseId);

    /// <summary>Адрес карточки фигуранта в интерфейсе профиля; <see langword="null"/> — перехода нет.</summary>
    /// <param name="personId">Фигурант (непрозрачный идентификатор профиля).</param>
    string? PersonCard(int personId);
}
