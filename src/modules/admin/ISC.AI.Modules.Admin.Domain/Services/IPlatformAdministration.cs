namespace ISC.AI.Modules.Admin.Domain.Services;

/// <summary>
/// ПОРТ ПРОФИЛЯ: кто вправе вести учётные записи и допуски и кто вправе читать журнал аудита.
/// Пакет умышленно не знает ни ролей, ни их названий: модель ролей — понятие профиля-эксплуатанта
/// (у «ИнспекторAI» четыре роли, у «Следствия» шесть), а право администрировать зависит от неё.
/// Без реализации приложение не запускается (тот же fail-closed, что у остальных пакетов, ТС-013).
/// </summary>
/// <remarks>
/// Почему право на журнал отдельным вопросом: по ТП-004 профиля «Следствие» аудит читает не только
/// Администратор, но и Офицер ИБ — роль, которая учётками и допусками не распоряжается. Разделение
/// прав на «ведение» и «чтение журнала» нужно, чтобы профиль мог выразить это без обходных путей.
///
/// Реализация обязана держать «режим первичной настройки» (пока в контуре нет ни одного администратора,
/// вести настройки может любой вошедший) — иначе на чистом развёртывании получается замок без ключа:
/// роль назначить некому, потому что назначение роли само требует роли.
/// </remarks>
public interface IPlatformAdministration
{
    /// <summary>Текущий субъект вправе вести учётные записи, допуски и справочники платформы.</summary>
    Task<bool> CanManageAsync(CancellationToken cancellationToken = default);

    /// <summary>Текущий субъект вправе читать неизменяемый журнал аудита (ТБ-030/032).</summary>
    Task<bool> CanViewAuditAsync(CancellationToken cancellationToken = default);
}
