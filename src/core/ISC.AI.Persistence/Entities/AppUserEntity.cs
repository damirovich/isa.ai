namespace ISC.AI.Persistence.Entities;

/// <summary>
/// Пользователь системы — субъект доступа. Схема <c>core</c>. Допуск (<see cref="ClearanceEntity"/>) —
/// обязательный вход решётки доступа (ТБ-002, ТБ-011, ТБ-012). Мягко удаляемый (история сохраняется).
/// </summary>
public class AppUserEntity : SoftDeletableEntity
{
    /// <summary>Уникальное имя входа.</summary>
    public required string UserName { get; set; }

    /// <summary>
    /// Идентификатор учётки во внешней системе идентификации (Э3-08) — привязка по значению, без FK
    /// через границу систем (ТО-инф-06). <c>null</c> — локальная учётка без внешней привязки.
    /// </summary>
    public string? ExternalId { get; set; }

    /// <summary>Отображаемое имя.</summary>
    public string? DisplayName { get; set; }

    /// <summary>Активен ли пользователь (немедленный отзыв — ТБ-016).</summary>
    public bool IsActive { get; set; } = true;

    /// <summary>
    /// Хеш пароля — PHC-строка Argon2id (<c>$argon2id$v=19$…</c>); <see langword="null"/> — локального
    /// пароля нет, вход возможен только через внешнюю систему (Э4-35 §6.5, переходный период).
    /// </summary>
    /// <remarks>
    /// САМ ПАРОЛЬ НЕ ХРАНИТСЯ И НЕ ЛОГИРУЕТСЯ (ТБ-043). Формат PHC совместим с хешами СКИД — та же
    /// библиотека libsodium, поэтому перенос учёток не требует смены пароля пользователями.
    /// </remarks>
    public string? PasswordHash { get; set; }

    /// <summary>
    /// Штамп безопасности: меняется при смене пароля и блокировке. Сессия, чей штамп разошёлся
    /// с текущим, завершается ревалидацией (ТБ-014/016).
    /// </summary>
    public string? SecurityStamp { get; set; }

    /// <summary>
    /// Пароль временный (выдан администратором при создании учётки или сбросе) — вход разрешён, но
    /// первым действием система обязана потребовать смену.
    /// </summary>
    /// <remarks>
    /// Отличие от внешнего провайдера СКИД, где такой вход просто ОТКЛОНЯЛСЯ: там сменить пароль
    /// можно было в самой СКИД, и ISC.AI сознательно не был «боковой дверью». Когда идентичность
    /// станет локальной, менять пароль будет негде, кроме как здесь, — отказ запер бы человека
    /// навсегда (Э4-35 §6.5).
    /// </remarks>
    public bool MustChangePassword { get; set; }

    /// <summary>
    /// Должность — справочная строка для узнавания человека в списках и отчётах.
    /// </summary>
    /// <remarks>
    /// На доступ НЕ влияет и влиять не должна: права определяются ролью и допуском, а должность —
    /// это подпись, а не полномочие. Перенос поля СКИД: там по должности искали в списке
    /// пользователей, потому что однофамильцев различить иначе нельзя.
    /// </remarks>
    public string? Position { get; set; }

    /// <summary>
    /// Причина отключения учётной записи; <see langword="null"/> — пока не отключалась.
    /// </summary>
    /// <remarks>
    /// Хранится ВМЕСТЕ с учёткой, а не только в журнале: администратор, открывший список через месяц,
    /// должен видеть «уволен» или «в отпуске» прямо в строке, не поднимая аудит. Значение остаётся
    /// и после повторного включения — как след того, что отключение было.
    /// </remarks>
    public string? DeactivationReason { get; set; }

    /// <summary>Когда учётная запись была отключена в последний раз (UTC).</summary>
    public DateTime? DeactivatedAt { get; set; }

    /// <summary>Допуск пользователя.</summary>
    public ClearanceEntity? Clearance { get; set; }
}
