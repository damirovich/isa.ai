namespace ISC.AI.Abstractions.Conversations;

/// <summary>Режим ответа чата.</summary>
public enum ChatMode
{
    /// <summary>
    /// Свободное общение и помощь (пояснения, формулировки, черновики). БЕЗ извлечения НПА и БЕЗ грунтовки;
    /// конкретные юридические утверждения и ссылки на НПА в этом режиме запрещены промптом — для них
    /// предлагается переключиться в <see cref="Grounded"/>. Ответ помечается как НЕ сверенный с НПА.
    /// </summary>
    Free = 0,

    /// <summary>
    /// Грунтованный режим (для вопросов по НПА и формирования документов): извлечение фрагментов с фильтром
    /// доступа → генерация → грунтовка (ссылки только из фрагментов, проверка валидатором) → аудит.
    /// </summary>
    Grounded = 1,
}
