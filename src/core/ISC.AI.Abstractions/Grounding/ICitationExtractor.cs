namespace ISC.AI.Abstractions.Grounding;

/// <summary>
/// Извлекает кандидатов-ссылки из текста вывода модели для грунтовки (ТБ-040). ДОМЕННЫЙ шов: что
/// считается «ссылкой», знает профиль (для «ИнспекторAI» — номера норм/статей НПА); ядро лишь
/// оркеструет проверку. По умолчанию ссылок не извлекает — профиль регистрирует свой экстрактор.
/// </summary>
public interface ICitationExtractor
{
    /// <summary>Возвращает найденные в выводе ссылки-кандидаты для проверки грунтовкой.</summary>
    IReadOnlyList<string> Extract(string output);
}
