namespace ISC.AI.Abstractions.Grounding;

/// <summary>
/// Приводит цитату/фрагмент к канонической форме перед сопоставлением — метод строже строкового
/// совпадения (ТО-мат-02, ADR-0008). ДОМЕННЫЙ шов: НПА-нормализацию (ru/ky-формы, сокращения, номера
/// норм/редакций) поставляет профиль. По умолчанию — нейтральная (регистр/пробелы).
/// </summary>
public interface ICitationNormalizer
{
    /// <summary>Возвращает канонизированную форму текста для сопоставления ссылок и фрагментов.</summary>
    string Normalize(string text);
}
