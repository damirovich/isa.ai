namespace ISC.AI.Abstractions.Security;

/// <summary>
/// Допуск конкретного пользователя по его идентификатору — для фоновой работы, которую пользователь запустил и которая
/// продолжается без его сессии (пакетный импорт архива, ADR-0041). Отвечает тем же <see cref="AccessContext"/>, что
/// получил бы сам пользователь при обращении из своей сессии.
/// </summary>
/// <remarks>
/// <para>
/// ИНВАРИАНТ БЕЗОПАСНОСТИ (ТБ-016, ТД-004): допуск читается из БД при КАЖДОМ вызове и не кэшируется. Фоновое задание
/// обязано спрашивать его перед каждым действием с данными: отзыв допуска или отключение учётной записи действует на
/// задание так же немедленно, как на живую сессию.
/// </para>
/// <para>
/// FAIL-CLOSED (ТБ-012/021): пользователь не найден, отключён или без действующего допуска — <see langword="null"/>,
/// а не «пустой» контекст. Это НЕ обход решётки: результат применяется теми же фильтрами (гриф, подразделения,
/// политика профиля), и шире допуска самого пользователя он не бывает. Кто вправе запускать работу от своего имени —
/// решает вызывающий сценарий по роли пользователя.
/// </para>
/// </remarks>
public interface IUserAccessReader
{
    /// <summary>
    /// Действующий контекст доступа пользователя либо <see langword="null"/>, если учётная запись не найдена,
    /// отключена или допуска нет.
    /// </summary>
    /// <param name="userId">Идентификатор пользователя в реестре <c>core.app_user</c>.</param>
    /// <param name="cancellationToken">Отмена.</param>
    Task<AccessContext?> ReadAsync(int userId, CancellationToken cancellationToken = default);
}
