using System.Linq.Expressions;

namespace ISC.AI.Abstractions.Security;

/// <summary>
/// Подключаемая профилем политика доступа: ДОПОЛНИТЕЛЬНОЕ доменное ограничение поверх неизменяемого
/// ядрового floor'а решётки. Возвращает EF-транслируемый предикат, который ретривер применяет
/// НА СТОРОНЕ БД (ТБ-020), уже ПОСЛЕ ядрового baseline.
/// </summary>
/// <remarks>
/// ИНВАРИАНТ РЕЖИМА: политика может ТОЛЬКО СУЖАТЬ доступ. Ядровой baseline (гриф ≤ допуск И
/// подразделение ∈ разрешённых) применяется ретривером ВСЕГДА и профилем не отключается — поэтому
/// даже ошибочная/широкая политика не выдаёт материал выше допуска (ТБ-020/021, GATE-1, ADR-0014).
/// По умолчанию — без дополнительных ограничений (реализация <c>AllowAllAccessPolicy</c> в ядре);
/// профиль регистрирует свою реализацию, чтобы доуточнить доступ под свою модель.
/// </remarks>
public interface IAccessPolicy
{
    /// <summary>
    /// Дополнительный предикат «ресурс разрешён субъекту» (EF-транслируемый), применяемый поверх
    /// ядрового baseline. <typeparamref name="T"/> — режимный ресурс (<see cref="IClassified"/>).
    /// </summary>
    Expression<Func<T, bool>> BuildFilter<T>(AccessContext subject) where T : IClassified;
}
