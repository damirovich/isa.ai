namespace ISC.AI.Abstractions.Security;

/// <summary>
/// Носитель режимных метаданных — гриф и подразделение, по которым работает решётка доступа (ТБ-020, ТБ-002).
/// Реализуется ресурсами корпуса (документ, чанк, эмбеддинг). Доменно-нейтрален: «гриф» и «подразделение» —
/// режимные примитивы платформы внутреннего контроля, а не понятия конкретного профиля.
/// </summary>
public interface IClassified
{
    /// <summary>Гриф (уровень секретности; выше — строже).</summary>
    short Classification { get; }

    /// <summary>Подразделение-владелец.</summary>
    int DivisionId { get; }
}
