namespace ISC.AI.Abstractions.Security;

/// <summary>
/// Порт внешней системы идентификации (Э3-08, ТБ-010/013/016): проверка учётных данных при входе и
/// чтение состояния учётки для ревалидации сессий. Реализация подключается хостом на точке композиции
/// (например, адаптер ведомственной БД пользователей); ядро конкретной системы не знает.
/// </summary>
/// <remarks>
/// ИНВАРИАНТ БЕЗОПАСНОСТИ (ТД-003): реализация обязана (а) не различать наружу причины отказа
/// («нет такого пользователя» / «неверный пароль» / «заблокирован» — один и тот же <c>null</c>,
/// без утечки через текст или заметную разницу времени ответа); (б) работать только внутри контура
/// (air-gap, ТБ-052); (в) не логировать пароль ни в каком виде (ТБ-043).
/// </remarks>
public interface IExternalIdentityProvider
{
    /// <summary>
    /// Проверяет пару логин/пароль во внешней системе. Возвращает подтверждённую учётку либо
    /// <c>null</c> при любом отказе (неизвестный логин, неверный пароль, блокировка) — без различения причин.
    /// </summary>
    Task<ExternalIdentity?> VerifyCredentialsAsync(string login, string password, CancellationToken cancellationToken = default);

    /// <summary>
    /// Возвращает текущее состояние учётки по внешнему идентификатору для ревалидации сессии
    /// (ТБ-014/016) либо <c>null</c>, если учётка не найдена (сессию завершить).
    /// </summary>
    Task<ExternalIdentityState?> GetStateAsync(string externalId, CancellationToken cancellationToken = default);
}
