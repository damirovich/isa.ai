namespace ISC.AI.Abstractions.Security;

/// <summary>
/// Идентификация текущего субъекта БЕЗ его допуска: отвечает на вопрос «кто вошёл», а не «что ему
/// можно» (последнее — <see cref="IAccessContextProvider"/>).
/// </summary>
/// <remarks>
/// Разделено НАМЕРЕННО, и это не дублирование. <see cref="IAccessContextProvider"/> fail-closed:
/// нет действующей записи допуска — исключение (ТБ-012/021), и это правильно для ЛЮБОЙ выдачи данных.
/// Но администрирование самого допуска подчиняться этому правилу не может: на ЧИСТОМ контуре записи
/// допуска нет ни у кого, поэтому экран, который её выдаёт, оказался бы недоступен всем — выдать
/// первый допуск было бы некому (замок без ключа, тот же класс отказа, что уже случался с ролями,
/// Э4-35 §6.4.1). Управление допусками и ролями опирается на этот порт: субъект известен из
/// аутентифицированной сессии, а право распоряжаться определяется РОЛЬЮ, а не наличием допуска.
///
/// ЧТО ЭТОТ ПОРТ НЕ ДЕЛАЕТ: он не даёт доступа к данным. Любая выдача содержимого (документы,
/// фрагменты, файлы) обязана по-прежнему идти через <see cref="IAccessContextProvider"/> и решётку
/// гриф/подразделение — иначе он превратился бы в обход разграничения.
/// </remarks>
public interface ISubjectProvider
{
    /// <summary>
    /// Идентификатор вошедшего пользователя в реестре <c>core.app_user</c>;
    /// <see langword="null"/> — не аутентифицирован либо субъект не отображается в локальный реестр
    /// (например dev-заглушка). Ноль и отрицательные значения не возвращаются.
    /// </summary>
    Task<int?> GetCurrentUserIdAsync(CancellationToken cancellationToken = default);
}
