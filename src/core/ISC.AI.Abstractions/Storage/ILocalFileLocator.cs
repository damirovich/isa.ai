namespace ISC.AI.Abstractions.Storage;

/// <summary>
/// Нейтральный порт ядра: путь к файлу хранилища на локальном диске для ВНЕШНЕГО процесса (ffmpeg,
/// ffprobe), которому нужен именно путь, а не поток (ADR-0028). Дополняет <see cref="IFileStorage"/>, не
/// заменяет его: чтение байтов по-прежнему идёт через <see cref="IFileStorage.OpenReadAsync"/>.
/// </summary>
/// <remarks>
/// ПОЧЕМУ ОТДЕЛЬНЫЙ ПОРТ. Вырезка кадра по времени — операция «по запросу» (каждый шаг покадрового просмотра);
/// копировать ради неё оригинал видео (до 200 МБ) во временный файл на каждый запрос нельзя ни по времени,
/// ни по ТБ-064 (лишние копии материала дела). Внешний процесс читает файл на месте, ТОЛЬКО на чтение.
/// ИНВАРИАНТЫ те же, что у <see cref="IFileStorage"/>: путь всегда под корнем хранилища (traversal
/// отклоняется), доступ к содержимому по этому пути НЕ проверяется — его проверяет владелец записи на
/// выдаче (ТБ-020/021). Хранилище, не имеющее локальных путей (сетевое, объектное), возвращает
/// <see langword="null"/> — вызывающий тогда работает через временную копию.
/// </remarks>
public interface ILocalFileLocator
{
    /// <summary>
    /// Полный локальный путь к файлу хранилища или <see langword="null"/>, если файла нет либо у хранилища нет
    /// локальных путей.
    /// </summary>
    /// <param name="storedFileName">Имя файла в хранилище (случайное + расширение).</param>
    /// <param name="category">Категория (каталог первого уровня).</param>
    /// <param name="subPath">Подкаталог внутри категории.</param>
    /// <exception cref="InvalidOperationException">Имя или путь выходят за пределы хранилища.</exception>
    string? TryGetLocalPath(string storedFileName, string category, string subPath);
}
