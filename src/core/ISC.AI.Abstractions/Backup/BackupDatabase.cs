namespace ISC.AI.Abstractions.Backup;

/// <summary>
/// База данных, которая входит в резервную копию (ТФ-АДМ-04, ТБ-082, ADR-0063). Регистрирует её слой данных, который
/// действительно подключён к хосту (ядро, пакет, профиль), — <c>services.AddSingleton(new BackupDatabase(...))</c> с той же
/// строкой подключения, что у его контекста. Одинаковые сервер, порт и база копируются один раз.
/// </summary>
/// <remarks>
/// ИНВАРИАНТЫ: копируется только то, чем пользуется работающая поставка, — строки подключения других профилей из общего
/// файла настроек в копию не попадают (ADR-0006: у профилей разные базы). Строка содержит пароль (ТБ-013), поэтому
/// <see cref="ToString"/> его не показывает — запись безопасно попадает в журнал и отладчик.
/// </remarks>
/// <param name="Name">Кто зарегистрировал (для сообщений): <c>core</c>, <c>docflow</c>, <c>media</c>, профиль.</param>
/// <param name="ConnectionString">Строка подключения — как у контекста этого слоя (с паролем из секретов).</param>
public sealed record BackupDatabase(string Name, string ConnectionString)
{
    /// <summary>Без строки подключения: в ней пароль.</summary>
    public override string ToString() => $"BackupDatabase {{ Name = {Name} }}";
}
