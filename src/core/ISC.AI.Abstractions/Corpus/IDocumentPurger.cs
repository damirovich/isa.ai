namespace ISC.AI.Abstractions.Corpus;

/// <summary>
/// Гарантированное удаление документа и всех его производных из корпуса ядра (ТБ-064): чанки,
/// эмбеддинги (pgvector), задания индексации — ФИЗИЧЕСКИ, без мягкого удаления. Применяется при
/// отзыве, ошибочной загрузке или изменении грифа. Факт удаления фиксируется в неизменяемом аудите
/// ДО удаления (fail-closed: уничтожения ДСП без записи в журнал не происходит).
/// </summary>
/// <remarks>
/// ОСОЗНАННЫЕ ГРАНИЦЫ (требуют подтверждения на приёмке режима):
/// <list type="bullet">
/// <item>Неизменяемый журнал аудита (ТБ-031, инвариант №4) НЕ удаляется. Тексты промптов/ответов,
/// попавшие в чувствительный payload аудита, остаются в журнале. Если требуется полное стирание ДСП
/// и из аудита — это отдельное режимное решение: хранить в аудите ссылки/хеши вместо сырого ДСП
/// (ТБ-032/ТБ-043), а не ослаблять неизменяемость журнала.</item>
/// <item>Профильные слабые связи (например <c>inspector.norm_document_link</c>) лежат за границей схемы
/// <c>core</c>; их чистит сам профиль своим хуком — ядро на профиль не ссылается (ТО-инф-06).</item>
/// <item>Физическое удаление файла-исходника — ответственность слоя хранилища. Ссылка на файл
/// (<c>StorageUri</c>) возвращается в результате, чтобы вызывающий удалил файл; файлового порта в
/// ядре пока нет.</item>
/// </list>
/// Авторизация (кто вправе удалять и что) — на вызывающей стороне (команда + поведение авторизации),
/// как и у прочих сценариев; порт принимает субъект лишь для записи в аудит.
/// </remarks>
public interface IDocumentPurger
{
    /// <summary>
    /// Физически удаляет документ и все его производные в корпусе ядра, записав факт в аудит.
    /// Идемпотентно: если документа нет — возвращается <see cref="DocumentPurgeResult.NotFound"/>
    /// без записи в аудит (удалять нечего).
    /// </summary>
    /// <param name="documentId">Идентификатор удаляемого документа (<c>core.document.id</c>).</param>
    /// <param name="subjectId">Субъект, инициировавший удаление (для аудита); <see langword="null"/> — неизвестен.</param>
    /// <param name="cancellationToken">Токен отмены.</param>
    Task<DocumentPurgeResult> PurgeAsync(
        int documentId, int? subjectId = null, CancellationToken cancellationToken = default);
}

/// <summary>Итог гарантированного удаления (ТБ-064).</summary>
/// <param name="Found">
/// <see langword="true"/> — документ существовал и удалён вместе с производными; <see langword="false"/> —
/// документа не было (идемпотентный вызов, ничего не менялось).
/// </param>
/// <param name="StorageUri">
/// Ссылка на файл-исходник для последующего удаления слоем хранилища; <see langword="null"/> — файла
/// не было или документ не найден.
/// </param>
public sealed record DocumentPurgeResult(bool Found, string? StorageUri = null)
{
    /// <summary>Документа с таким идентификатором нет — удалять нечего.</summary>
    public static readonly DocumentPurgeResult NotFound = new(Found: false);
}
