namespace ISC.AI.Abstractions.Ingestion;

/// <summary>
/// Известные ядру значения поля «источник» документа корпуса (<c>core.document.source</c>).
/// Ядро источники не интерпретирует — это метка ДЛЯ ПОТРЕБИТЕЛЕЙ корпуса, которым важно различать,
/// откуда пришёл текст. Константа живёт в нейтральном слое, потому что её пишет один модуль
/// (документооборот), а читает другой потребитель (картотека НПА профиля), и ссылаться друг на
/// друга они не могут (ADR-0017).
/// </summary>
public static class CorpusSources
{
    /// <summary>
    /// Документ пришёл из модуля документооборота (индексация карточки и файлов документа).
    /// Такие документы — делопроизводство, а не нормативный материал: картотека НПА не предлагает
    /// их к привязке, иначе утрата силы нормы пряталa бы из поиска чьё-то поручение.
    /// </summary>
    public const string DocFlow = "Документооборот";
}
