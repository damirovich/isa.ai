namespace ISC.AI.Abstractions.Ingestion;

/// <summary>
/// Порт конвейера загрузки документов в корпус (чанкинг, векторизация, индексация — ТО-мат-03, ТО-инф-07).
/// </summary>
/// <remarks>
/// ИНВАРИАНТ БЕЗОПАСНОСТИ (ТБ-024, ТО-инф-03): документ/чанк без явно установленных ГРИФА и
/// ПОДРАЗДЕЛЕНИЯ ОТКЛОНЯЕТСЯ и не попадает в индекс; гриф по умолчанию — максимально ограничительный,
/// а не открытый. Порт НЕ определяет гриф из содержимого — он лишь проверяет его наличие (его задаёт
/// оператор/источник до вызова). Операция ИДЕМПОТЕНТНА: повторная загрузка того же содержимого не
/// создаёт дублей (ТНД-002).
/// </remarks>
public interface IIngestionPort
{
    /// <summary>
    /// Принимает документ и индексирует его чанки. При отсутствии явного грифа/подразделения —
    /// отказ без индексации (fail-closed, ТБ-024).
    /// </summary>
    Task<IngestionResult> IngestAsync(IngestionRequest request, CancellationToken cancellationToken = default);
}
