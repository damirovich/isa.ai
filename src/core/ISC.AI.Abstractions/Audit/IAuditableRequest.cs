namespace ISC.AI.Abstractions.Audit;

/// <summary>
/// Маркер аудируемого сценария Mediator (ТБ-030, §5.1.6.15): сквозное <c>AuditBehavior</c> пишет запись
/// неизменяемого журнала для КАЖДОГО такого запроса. Аудит становится инвариантом конвейера, а не
/// дисциплиной хендлера (которую легко забыть — как забыли для генерации и загрузки корпуса).
/// </summary>
public interface IAuditableRequest
{
    /// <summary>Тип аудируемого действия.</summary>
    AuditAction AuditAction { get; }

    /// <summary>Краткое описание для журнала (чувствительное содержимое — ТБ-032). Опционально.</summary>
    string? AuditSummary => null;

    /// <summary>
    /// Объявленный гриф затронутого объекта, если известен ДО выполнения (напр. гриф загружаемого документа,
    /// который может быть ВЫШЕ допуска оператора). Запись журнала классифицируется не ниже
    /// <c>max(этот гриф, допуск субъекта)</c>. <c>null</c> — классифицировать только по допуску субъекта.
    /// </summary>
    short? AuditClassification => null;
}
