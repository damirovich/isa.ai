namespace ISC.AI.Abstractions.Audit;

/// <summary>
/// Исход операции в записи журнала аудита (ТБ-080, ADR-0066). Записи до обновления исхода не несут — это «не записано»,
/// а не успех: прежний журнал писался и при ошибках, и при отменах.
/// </summary>
public enum AuditOutcome : short
{
    /// <summary>Операция выполнена.</summary>
    Success = 0,

    /// <summary>Отказ: система не выполнила операцию по правилам — нет права, не найдено, не прошла проверка, конфликт.</summary>
    Denied = 1,

    /// <summary>Ошибка: операция упала — исключение, внутренняя ошибка, недоступна внешняя зависимость.</summary>
    Error = 2,

    /// <summary>Отмена: операция прервана до завершения (пользователь отменил или ушёл со страницы).</summary>
    Cancelled = 3,
}
