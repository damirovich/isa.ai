namespace ISC.AI.Abstractions.Modules;

/// <summary>
/// Какие разделы профиля показывать ТЕКУЩЕМУ пользователю в меню (ТС-007, ТП-004). Роли знает профиль, ядро — нет:
/// хост спрашивает этот порт и прячет остальное, а при переходе по прямой ссылке на скрытый раздел показывает
/// «Раздел недоступен для вашей роли». Реализация по умолчанию (в хосте) показывает всё — профиль без ролей
/// ничего не прячет.
/// </summary>
/// <remarks>
/// Это ИНТЕРФЕЙСНОЕ правило, не граница безопасности: права на действия проверяет сервер в каждом сценарии
/// (ТБ-012). Поэтому профиль обязан прятать ровно то, что сервер и так запретит, — не больше (иначе человек не
/// найдёт доступное) и не меньше (иначе увидит раздел, где любое действие получит отказ).
/// </remarks>
public interface IModuleVisibility
{
    /// <summary>Идентификаторы видимых текущему пользователю модулей из перечисленных.</summary>
    /// <param name="modules">Модули профиля (реестр меню).</param>
    /// <param name="cancellationToken">Токен отмены.</param>
    Task<IReadOnlySet<string>> GetVisibleModuleIdsAsync(
        IReadOnlyCollection<IModule> modules, CancellationToken cancellationToken = default);
}
