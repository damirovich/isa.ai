namespace ISC.AI.Abstractions.AI;

/// <summary>Шаблон задачного промпта профиля: ключ и текст-шаблон (Scriban).</summary>
public sealed record PromptTemplate(string Key, string Text);

/// <summary>
/// Поставщик задачных промптов профиля. Промпты хранятся файлами-шаблонами в прикладном слое
/// профиля (не в UI и не в коде C#) и загружаются по ключу (ТО-лнг-03).
/// </summary>
/// <remarks>
/// ИНВАРИАНТ (ТБ-041): системная часть промпта с правилом грунтовки задаётся ядром и через
/// этот контракт НЕ предоставляется и не может быть переопределена профилем. Итоговый промпт
/// собирается ядром как «системный (ядро) + задачный (профиль) + данные».
/// </remarks>
public interface IPromptProvider
{
    /// <summary>
    /// Возвращает шаблон задачного промпта по ключу (например, <c>"generator.act"</c>).
    /// Бросает исключение, если шаблон не найден: молчаливая подмена пустым/произвольным
    /// текстом недопустима.
    /// </summary>
    PromptTemplate GetTaskPrompt(string promptKey);
}
