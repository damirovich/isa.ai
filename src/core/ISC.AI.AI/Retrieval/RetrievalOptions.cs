namespace ISC.AI.AI.Retrieval;

/// <summary>
/// Метрика ранжирования по релевантности (ТО-мат-04, задаётся конфигурацией). Во всех метриках меньше —
/// ближе (единый порядок сортировки). По умолчанию — <see cref="Cosine"/>: совпадает с HNSW-индексом
/// эмбеддингов (<c>vector_cosine_ops</c>), поэтому используется индекс. Иная метрика ранжирует КОРРЕКТНО,
/// но существующий индекс к ней не подходит (запрос идёт seq-scan) — для прод-нагрузки нужен индекс с
/// соответствующим operator class (миграция).
/// </summary>
public enum RetrievalMetric
{
    /// <summary>Косинусное расстояние (оператор <c>&lt;=&gt;</c>). По умолчанию; совпадает с HNSW-индексом.</summary>
    Cosine = 0,

    /// <summary>Евклидово расстояние L2 (оператор <c>&lt;-&gt;</c>).</summary>
    Euclidean = 1,

    /// <summary>Отрицательное скалярное произведение (оператор <c>&lt;#&gt;</c>): меньше — ближе.</summary>
    NegativeInnerProduct = 2,
}

/// <summary>
/// Параметры извлечения (ТО-мат-04: «ранжирование результатов И пороги отсечения по релевантности задаются
/// конфигурацией»). Значения читаются из секции <c>Retrieval</c> конфигурации хоста, не хардкодятся.
/// </summary>
/// <param name="MaxDistance">
/// Порог отсечения по релевантности — максимальное расстояние В ЕДИНИЦАХ ВЫБРАННОЙ <paramref name="Metric"/>
/// (для Cosine: 0 — идентично, больше — дальше; см. <see cref="ISC.AI.Abstractions.Retrieval.RetrievedChunk.Score"/>).
/// Фрагменты дальше порога не возвращаются, даже если <c>topK</c> ещё не исчерпан. При <see langword="null"/>
/// отсечения нет — безопасный дефолт до калибровки на реальном корпусе и модели эмбеддингов (Э1, КИ-03).
/// </param>
/// <param name="Metric">
/// Метрика ранжирования (ТО-мат-04). По умолчанию <see cref="RetrievalMetric.Cosine"/> — совпадает с
/// HNSW-индексом; смена метрики меняет порядок выдачи и смысл <paramref name="MaxDistance"/>.
/// </param>
/// <param name="HnswEfSearch">
/// Широта обхода HNSW-графа при поиске (<c>hnsw.ef_search</c>, ТБ-022): сколько кандидатов индекс
/// рассматривает до отбора top-K. Дефолт PostgreSQL (40) доказанно ПРОПУСКАЕТ малые семантические
/// «острова» — группы из нескольких документов, непохожих на основной корпус (инцидент 26.08.2026:
/// загруженный документ находился точным сканом и терялся индексным). Значение 200 в паре со сборкой
/// индекса <c>ef_construction=512</c> возвращает такие документы; ретривер выставляет его на каждую
/// поисковую транзакцию. Без HNSW-индекса настройка безвредна. Диапазон 10–1000 (ограничение pgvector).
/// </param>
public sealed record RetrievalOptions(
    double? MaxDistance = null,
    RetrievalMetric Metric = RetrievalMetric.Cosine,
    int HnswEfSearch = 200)
{
    /// <summary>Без отсечения по релевантности, метрика по умолчанию (Cosine) — поведение до калибровки.</summary>
    public static readonly RetrievalOptions None = new();
}
