namespace ISC.AI.AI.Retrieval;

/// <summary>
/// Пороги извлечения (ТО-мат-04: «ранжирование результатов и пороги отсечения по релевантности задаются
/// конфигурацией»). Значения читаются из секции <c>Retrieval</c> конфигурации хоста, не хардкодятся.
/// </summary>
/// <param name="MaxDistance">
/// Порог отсечения по релевантности — максимальное косинусное расстояние между запросом и фрагментом
/// (0 — идентично, больше — дальше; см. <see cref="ISC.AI.Abstractions.Retrieval.RetrievedChunk.Score"/>).
/// Фрагменты дальше порога не возвращаются, даже если <c>topK</c> ещё не исчерпан. При
/// <see langword="null"/> отсечения нет — безопасный дефолт до калибровки на реальном корпусе и модели
/// эмбеддингов (Э1, КИ-03): без данных о фактическом распределении расстояний угадывать порог нельзя.
/// </param>
public sealed record RetrievalOptions(double? MaxDistance = null)
{
    /// <summary>Без отсечения по релевантности — поведение по умолчанию, пока порог не откалиброван.</summary>
    public static readonly RetrievalOptions None = new();
}
