namespace ISC.AI.AI.Rag;

/// <summary>
/// Параметры генерации ядра (зрелость ТН-003): детерминизм и границы вывода для АУДИРУЕМОГО ассистента.
/// Читаются из секции конфигурации <c>Llm:Generation</c>, не хардкодятся. Безопасные умолчания —
/// детерминированная генерация (температура 0) и ограниченная длина ответа.
/// </summary>
/// <param name="Temperature">
/// Температура сэмплирования. По умолчанию <c>0</c> — детерминированно и ВОСПРОИЗВОДИМО: одинаковый запрос
/// по одному корпусу даёт одинаковый ответ. Критично для доверия к неизменяемому журналу и минимизации
/// галлюцинаций в юридическом контексте (полагаться на дефолт сервера ~0.7 — неверно).
/// </param>
/// <param name="TopP">Nucleus sampling. <see langword="null"/> — не задавать (дефолт сервера).</param>
/// <param name="MaxOutputTokens">Верхняя граница длины ответа — защита от неограниченной генерации.</param>
/// <param name="Seed">Фиксированный seed воспроизводимости (если сервер поддерживает). <see langword="null"/> — не задавать.</param>
/// <param name="PromptTokenBudget">
/// Бюджет токенов на ВЕСЬ промпт (системное правило + задачный промпт + фрагменты + запрос). Если оценка
/// превышает бюджет, младшие по релевантности фрагменты отбрасываются (с записью в лог — не тихо), а
/// грунтовка выполняется по ФАКТИЧЕСКИ отправленным фрагментам. <see langword="null"/> — без гварда бюджета
/// (безопасный дефолт до калибровки под окно конкретной модели, как <c>Retrieval:MaxDistance</c>).
/// </param>
/// <param name="CharsPerToken">
/// Консервативная оценка «символов на токен» для приблизительного подсчёта БЕЗ реального токенизатора модели.
/// Меньше — осторожнее (раньше усечёт). Для кириллицы ~2.5.
/// </param>
public sealed record GenerationOptions(
    float Temperature = 0f,
    float? TopP = null,
    int? MaxOutputTokens = 4096,
    long? Seed = null,
    int? PromptTokenBudget = null,
    double CharsPerToken = 2.5)
{
    /// <summary>Детерминированная генерация с ограниченной длиной, без гварда бюджета (до калибровки).</summary>
    public static readonly GenerationOptions Default = new();
}
