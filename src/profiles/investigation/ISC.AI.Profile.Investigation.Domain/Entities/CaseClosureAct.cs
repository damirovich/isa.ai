using ISC.AI.Abstractions.Entities;

namespace ISC.AI.Profile.Investigation.Domain.Entities;

/// <summary>
/// Акт об удалении биометрических шаблонов по закрытию дела (<c>investigation.case_closure_act</c>,
/// ТФ-ДЕЛ-04, ТБ-074; увязка с УПК ст. 224).
/// </summary>
/// <remarks>
/// ЗАЧЕМ ОТДЕЛЬНАЯ ЗАПИСЬ, ЕСЛИ ЕСТЬ ЖУРНАЛ АУДИТА. Журнал фиксирует удаление по каждому носителю —
/// он полон, но не предъявляем: это технический след, доступный офицеру ИБ и администратору. Акт —
/// документ ДЕЛА: он лежит в деле, виден следователю и руководителю в карточке и отвечает на
/// единственный вопрос надзора «чем подтверждается, что биометрия по закрытому делу уничтожена».
/// Поэтому акт хранит итоговые числа, а не ссылки на удалённые строки: тех строк уже нет, и любая
/// ссылка на них была бы недостоверной.
///
/// ОТСУТСТВИЕ АКТА У ЗАКРЫТОГО ДЕЛА — ЗНАЧИМЫЙ ФАКТ, а не пустое поле: значит регламент не отработал
/// (например, был недоступен журнал аудита, и удаление правильно не состоялось — fail-closed).
/// Карточка дела показывает это предупреждением, регламент повторяется закрытием дела ещё раз.
/// </remarks>
public class CaseClosureAct : AuditableEntity
{
    /// <summary>Дело (FK внутри схемы).</summary>
    public int CaseId { get; set; }

    /// <summary>Навигация к делу.</summary>
    public CaseFile? Case { get; set; }

    /// <summary>Когда регламент выполнен (UTC).</summary>
    public DateTime ExecutedAt { get; set; }

    /// <summary>Кто закрыл дело и тем запустил регламент (слабая ссылка на пользователя ядра).</summary>
    public int? ExecutedByUserId { get; set; }

    /// <summary>Сколько носителей дела было на момент закрытия — они СОХРАНЕНЫ (ТФ-ДЕЛ-04).</summary>
    public int MediaAssetsTotal { get; set; }

    /// <summary>По скольким носителям снята биометрия (у остальных её и не было).</summary>
    public int AssetsAffected { get; set; }

    /// <summary>Сколько шаблонов лиц удалено — столько векторов ушло из индекса поиска.</summary>
    public int TemplatesRemoved { get; set; }

    /// <summary>Сколько файлов вырезок лиц удалено из хранилища.</summary>
    public int CropsRemoved { get; set; }
}
