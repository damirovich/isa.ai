namespace ISC.AI.Profile.Investigation.Domain.Services;

/// <summary>
/// Правила хранения биометрии профиля «Следствие» (ТБ-074, ТБ-078, ADR-0024): что происходит с
/// шаблонами лиц при закрытии дела.
/// </summary>
/// <remarks>
/// ПОЧЕМУ ЭТО НАСТРОЙКА, А НЕ КОНСТАНТА. Сроки хранения и удаления биометрии задаёт ВЕДОМСТВЕННЫЙ АКТ
/// эксплуатанта (ТБ-078, ПОДГ-09), а регламент эталонной базы (ТО-орг-03) утверждает заказчик — значит
/// решение «удалять по закрытию дела или хранить» принимается вне кода, и код обязан уметь оба варианта.
///
/// ЗНАЧЕНИЕ ПО УМОЛЧАНИЮ — ХРАНИТЬ (решение заказчика 18.09.2026). Причина эксплуатационная и весомая:
/// человек, проходивший по оконченному делу, попадается снова, и материалы прежнего дела — самое
/// ценное, что поиск может дать следователю нового дела; при удалении шаблонов такой поиск невозможен
/// в принципе. Сужение области при этом сохранено: закрытые дела не попадают в поиск сами собой —
/// оператор включает их осознанно, и включение фиксируется в журнале (ТФ-ПЛ-05, ТБ-072).
///
/// ЧЕГО ЭТА НАСТРОЙКА НЕ МЕНЯЕТ: решётку доступа (ТБ-020/021 — гриф и подразделение), сужение по делам
/// субъекта (ТБ-071), правило двух лиц (ТБ-073) и аудит каждого поиска (ТБ-072). Хранение шаблонов
/// дольше закрытия дела расширяет область поиска, но не круг тех, кому материалы видны.
///
/// ВНИМАНИЕ ПРИ ПРИЁМКЕ: при <see cref="PurgeTemplatesOnCaseClosure"/> = <see langword="false"/>
/// требование ТБ-074 в части «шаблоны материалов дела удаляются при закрытии дела» и половина GATE-6
/// «закрытие дела удаляет …» не выполняются — по решению эксплуатанта. Отклонение должно быть отражено
/// в ведомственном акте и оценке воздействия (ТБ-078), а формулировка ТБ-074 в ДОК-12 приведена
/// в соответствие.
/// </remarks>
/// <param name="PurgeTemplatesOnCaseClosure">
/// Удалять шаблоны лиц и вырезки при закрытии дела (регламент ТБ-074 с актом). По умолчанию
/// <see langword="false"/> — шаблоны хранятся, пока хранится дело.
/// </param>
public sealed record InvestigationRetentionOptions(bool PurgeTemplatesOnCaseClosure = false)
{
    /// <summary>Ключ конфигурации регламента удаления шаблонов по закрытию дела.</summary>
    public const string PurgeOnClosureKey = "Investigation:Retention:PurgeTemplatesOnCaseClosure";
}
