using ISC.AI.Profile.Inspector.Domain.Enums;

namespace ISC.AI.Profile.Inspector.Domain.Entities;

/// <summary>
/// Подразделение — объект контроля с иерархией ТУ→РО (§4.2). Схема <c>inspector</c>. Сопоставляется с
/// ПЛОСКИМ справочником подразделений СКИД ПО ЗНАЧЕНИЮ через <see cref="Code"/> (без FK через границу схем,
/// ТО-инф-06). Иерархию ведёт «ИнспекторAI» — в СКИД её нет.
/// </summary>
public class Division : AuditableEntity
{
    /// <summary>Наименование подразделения.</summary>
    public required string Name { get; set; }

    /// <summary>
    /// Код подразделения — условное обозначение (§4.2). Исторически был ключом сопоставления
    /// с внешней СКИД; после слияния СКИД внутрь системы (Э4-35) функциональной сверки нет —
    /// код показывается людям. Пустой при создании назначается автоматически («Т-{id}»/«Л-{id}»
    /// по типу); вписанный вручную (официальное обозначение) хранится как есть.
    /// </summary>
    public string? Code { get; set; }

    /// <summary>
    /// Тип подразделения (§4.2): территориальное либо линейное. Существующие записи миграцией
    /// помечены территориальными (историческое умолчание справочника); тип правится в справочнике.
    /// Нужен аналитике архива (ТФ-АРХ-03 — сравнение территориальных и линейных).
    /// </summary>
    public DivisionKind Kind { get; set; } = DivisionKind.Territorial;

    /// <summary>Родительское подразделение (null — верхний уровень, напр. ТУ). FK внутри схемы inspector.</summary>
    public int? ParentId { get; set; }

    /// <summary>Навигация к родителю.</summary>
    public Division? Parent { get; set; }

    /// <summary>
    /// Действующее ли подразделение. Неактивное НЕ предлагается при регистрации и в назначениях,
    /// но остаётся в справочнике.
    /// </summary>
    /// <remarks>
    /// Нужно рядом с удалением, а не вместо него: расформированное подразделение удалить НЕЛЬЗЯ —
    /// за ним числятся документы и поручения, и их владелец превратился бы в число без имени.
    /// Признак активности выводит его из обращения, сохраняя историю. Удаление остаётся только для
    /// ошибочно заведённых, за которыми ничего нет.
    /// </remarks>
    public bool IsActive { get; set; } = true;

    /// <summary>Дочерние подразделения (вплоть до районного отдела, РО).</summary>
    public ICollection<Division> Children { get; set; } = [];
}
