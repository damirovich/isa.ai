#!/usr/bin/env bash
# Проверка целостности пакета «ИнспекторAI» после переноса за периметр (ТБ-051, ТИ-002).
# Запускать ДО установки, на сервере в контуре:   bash verify.sh [--log /путь/к/журналу-переноса.txt]
#
# Что проверяется: каждый файл пакета совпадает с SHA256SUMS (хеши посчитаны при сборке, вне контура), нет ни
# отсутствующих, ни ЛИШНИХ файлов (подложенный файл — тоже отказ). Код возврата 0 — пакет цел; иначе устанавливать
# нельзя, перенос повторяется. С ключом --log итог дописывается строкой в журнал переноса (кто, когда, что, вердикт) —
# сам журнал организационный и ведётся Заказчиком.
set -euo pipefail

cd "$(dirname "$(readlink -f "$0")")"

log_file=""
if [[ "${1:-}" == "--log" ]]; then
    log_file="${2:?после --log укажите файл журнала переноса}"
fi

if [[ ! -f SHA256SUMS ]]; then
    echo "ОТКАЗ: в пакете нет SHA256SUMS — проверить целостность нечем." >&2
    exit 2
fi

version="$(cat VERSION 2>/dev/null | head -n 1 || echo 'неизвестна')"
verdict="ЦЕЛ"
problems=()

# 1) Хеши всех перечисленных файлов (отсутствующий файл sha256sum тоже считает ошибкой).
if ! sha256sum --quiet --strict -c SHA256SUMS; then
    verdict="ПОВРЕЖДЁН"
    problems+=("хеши не совпали или файлы отсутствуют (список выше)")
fi

# 2) Лишние файлы: всё, что лежит в пакете, обязано быть в манифесте. Имя в строке sha256sum начинается с 67-го символа
#    (64 знака хеша, пробел и признак режима).
extra="$(comm -13 <(cut -c67- SHA256SUMS | sort) <(find . -type f ! -name SHA256SUMS -printf '%P\n' | sort))"
if [[ -n "$extra" ]]; then
    verdict="ПОВРЕЖДЁН"
    problems+=("лишние файлы вне манифеста:")
    while IFS= read -r line; do problems+=("  $line"); done <<< "$extra"
fi

files="$(wc -l < SHA256SUMS)"
if [[ "$verdict" == "ЦЕЛ" ]]; then
    echo "Пакет $version цел: $files файлов совпали с SHA256SUMS, лишних нет."
else
    echo "ОТКАЗ: пакет $version повреждён — устанавливать нельзя." >&2
    printf '  %s\n' "${problems[@]}" >&2
fi

if [[ -n "$log_file" ]]; then
    printf '%s\t%s\tпакет %s\tфайлов %s\t%s\n' \
        "$(date '+%Y-%m-%d %H:%M:%S')" "${SUDO_USER:-$(id -un)}" "$version" "$files" "$verdict" >> "$log_file"
fi

[[ "$verdict" == "ЦЕЛ" ]]
